#!/usr/bin/env node
// Regenerates src/lib/server/builtin-skills.ts from examples/skills/<name>/SKILL.md.
// The seed ships these skills; the Markdown files are the source of truth.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const examples = join(here, "../../../examples/skills");
const out = join(here, "../src/lib/server/builtin-skills.ts");

// Order is the seed order; the first two are enabled because every paying agent needs them.
const SKILLS = [
  ["agent-rails-payments", "\\u{1F6E1}\\u{FE0F}", true],
  ["vendor-checkout", "\\u{1F9FE}", true],
  ["oracle-pricing", "\\u{1F4C8}", false],
  ["document-notary", "\\u{1F4DC}", false],
  ["compute-credits", "\\u{1F9EE}", false],
];

const rows = SKILLS.map(([slug, icon, enabled]) => {
  const text = readFileSync(join(examples, slug, "SKILL.md"), "utf8");
  const match = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(text);
  if (!match) throw new Error(`${slug}: no frontmatter`);
  const fields = Object.fromEntries(
    match[1].split("\n").map((line) => {
      const at = line.indexOf(": ");
      return [line.slice(0, at), line.slice(at + 2)];
    }),
  );
  return `  {
    id: ${JSON.stringify(`s_${slug.replaceAll("-", "_")}`)},
    name: ${JSON.stringify(fields.name)},
    description: ${JSON.stringify(fields.description)},
    icon: "${icon}",
    scope: "global",
    scopeName: null,
    enabled: ${enabled},
    demo: false,
    content: ${JSON.stringify(match[2].trim())},
  },`;
});

writeFileSync(
  out,
  `/**
 * The skills under examples/skills, as seed rows. Generated by
 * scripts/sync-builtin-skills.mjs (pnpm --filter @agent-rails/dashboard skills:sync);
 * builtin-skills.test.ts fails when this file and the Markdown drift.
 */

import type { StoredSkill } from "@/lib/schema";

export const BUILTIN_SKILLS: StoredSkill[] = [
${rows.join("\n")}
];
`,
);
console.log(`wrote ${out}`);
